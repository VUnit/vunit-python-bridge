"""
The base directory that ``base_path`` of ``python_pkg`` returns: set by ``set_relative_file_base``
in the run script or by the environment variable ``VUNIT_PYTHON_BRIDGE_FILE_BASE``, and given to
VHDL in a generated package.
"""

import logging
import os
from pathlib import Path

from .bridge import _write_if_changed

# Name of the generated VHDL package holding the base directory, used by python_pkg (base_path)
FILE_BASE_PACKAGE = "python_file_base_pkg"

# The environment variable setting the directory of base_path when the run script cannot. It takes
# precedence over set_relative_file_base so that whoever runs a shared run script can override it.
FILE_BASE_VARIABLE = "VUNIT_PYTHON_BRIDGE_FILE_BASE"

LOGGER = logging.getLogger(__name__)

# The directory set by set_relative_file_base, None when unset, and whether setup has run, after
# which the directory is in the generated package and can no longer be changed
_relative_file_base = None
_setup_done = False


def set_relative_file_base(directory):
    """
    Set the directory that ``base_path`` of ``python_pkg`` returns, for VHDL to join file names to.

    Call it in the run script before ``vu.add_package("vunit-python-bridge", ...)``. A relative
    directory is taken from the current working directory at the time of the call.

    :param directory: An existing directory, a ``str`` or a ``Path``.
    """
    global _relative_file_base  # pylint: disable=global-statement

    if _setup_done:
        raise RuntimeError(
            'set_relative_file_base() must be called before vu.add_package("vunit-python-bridge", ...), '
            "the package has already been set up"
        )
    path = Path(directory).resolve()
    if not path.is_dir():
        raise ValueError(f"The relative file base {str(directory)!r} is not an existing directory")
    _relative_file_base = path


def _vhdl_string_literal(text):
    """
    A VHDL expression of type string for the UTF-8 bytes of a text, in ASCII: printable characters
    in a literal with its quotes doubled, other bytes as character'val(n).
    """
    parts = []
    literal = ""
    for byte in text.encode("utf-8"):
        if 0x20 <= byte <= 0x7E:
            literal += '""' if byte == ord('"') else chr(byte)
        else:
            if literal:
                parts.append(f'"{literal}"')
                literal = ""
            parts.append(f"character'val({byte})")
    if literal or not parts:
        parts.append(f'"{literal}"')
    if not parts[0].startswith('"'):
        # A string expression rather than a lone character
        parts.insert(0, '""')
    return " & ".join(parts)


def _file_base_package_text(directory):
    """
    Content of the generated python_file_base_pkg.vhd.
    """
    value = "" if directory is None else directory.as_posix()
    return f"""\
-- Generated by vunit_python_bridge.setup. Do not edit.
--
-- The directory set by the environment variable {FILE_BASE_VARIABLE} or by
-- vunit_python_bridge.set_relative_file_base() in the run script, empty when neither is set.
-- base_path of python_pkg returns it.
package {FILE_BASE_PACKAGE} is
  constant p_relative_file_base : string := {_vhdl_string_literal(value)};
end package;
"""


def _file_base():
    """
    The directory of base_path: that of the environment variable if it is set and not empty,
    otherwise that of set_relative_file_base, None when neither is set.
    """
    value = os.environ.get(FILE_BASE_VARIABLE, "")
    if value == "":
        return _relative_file_base

    directory = Path(value).resolve()
    if not directory.is_dir():
        raise ValueError(f"The environment variable {FILE_BASE_VARIABLE}={value!r} is not an existing directory")
    if _relative_file_base is not None and _relative_file_base != directory:
        LOGGER.warning(
            "The environment variable %s=%s takes precedence over set_relative_file_base(%r)",
            FILE_BASE_VARIABLE,
            value,
            str(_relative_file_base),
        )
    return directory


def add_file_base_package(context):
    """
    Generate python_file_base_pkg and add it to the library of the package.
    """
    global _setup_done  # pylint: disable=global-statement

    path = Path(context.output_path) / "python_bridge" / "vhdl" / f"{FILE_BASE_PACKAGE}.vhd"
    _write_if_changed(path, _file_base_package_text(_file_base()))
    context.add_source_files(context.library.name, [path])
    _setup_done = True

